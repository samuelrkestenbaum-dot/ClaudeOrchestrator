// STEP 1 — what are the extra Gravito turns actually DOING?
//
// EXP-0007 established that every intervention moving work out of the model's
// context RAISED turns (A +19, B +35, ABC +15 on T01). "Turns went up" is not a
// finding you can design against. This asks what those turns contain.
//
// CLASSIFIED BY STRUCTURE, NOT BY CONTENT. Every classifier in this work that
// matched result text ended up matching the thing it was describing -- the gate
// comments, the process guard, the pgrep pattern, the no-pointer check. So each
// turn is classified by (tool name, requested path, result error flag,
// position relative to a refusal). None of those can match a file's prose.
//
// AMBIGUITY IS PRESERVED. A turn with no structural signal is `unclassified`,
// not forced into the nearest bucket. The operator's instruction was explicit:
// do not force every turn into a category when the evidence is ambiguous.

import fs from "node:fs";
import path from "node:path";
import { classifyRead } from "./implementation-reads.mjs";

export const CAUSES = [
  "gravito_implementation_read",   // Read of build-os/ .claude/ CLAUDE.md
  "authority_gate_roundtrip",      // a mutation-capable tool refused by a hook
  "gravito_search",                // Grep/Glob aimed at substrate paths
  "routing_bookkeeping",           // Bash invoking route-task / routing-check, or writing a receipt
  "subagent_dispatch",             // Task/Agent
  "verification",                  // Bash running tsc / npm test / the verify command
  "tool_retry",                    // an errored tool call that is not a gate refusal
  "product_work",                  // Read/Edit/Write on non-substrate paths
  "unclassified",
];

const SUBSTRATE = /(^|\/)(build-os|\.claude)(\/|$)|(^|\/)CLAUDE\.md$/;

/** Classify one tool_use + its result. Structure only. */
export function classifyTurn(name, input, resultIsError, resultText) {
  const p = input?.file_path ?? input?.path ?? null;
  const cmd = typeof input?.command === "string" ? input.command : "";
  const pattern = input?.pattern ?? input?.glob ?? "";
  const searchPath = input?.path ?? "";

  if (name === "Task" || name === "Agent") return "subagent_dispatch";

  if (name === "Read") {
    const k = classifyRead("Read", p);
    return k === "implementation" ? "gravito_implementation_read"
         : k === "product" ? "product_work" : "unclassified";
  }

  if (name === "Grep" || name === "Glob") {
    return SUBSTRATE.test(String(searchPath)) || SUBSTRATE.test(String(pattern))
      ? "gravito_search" : "product_work";
  }

  if (name === "Edit" || name === "Write" || name === "MultiEdit") {
    if (resultIsError) return "authority_gate_roundtrip";
    if (p && SUBSTRATE.test(p.replace(/^.*?(?:exp000\d-arm|empathiq-website)\//, ""))) return "routing_bookkeeping";
    return "product_work";
  }

  if (name === "Bash") {
    // A refused mutation-capable call is a gate round-trip. Detected by the
    // ERROR FLAG plus the harness's own hook prefix, which is generated by the
    // runtime rather than drawn from any file in the tree.
    if (resultIsError && /^(PreToolUse|PostToolUse):/.test(String(resultText || "").trimStart()))
      return "authority_gate_roundtrip";
    if (/\btsc\b|npm (run )?(test|build)|vitest|jest/.test(cmd)) return "verification";
    if (/route-task\.sh|routing-check\.sh|record-degradation\.sh/.test(cmd)) return "routing_bookkeeping";
    if (/build-os\/|\.claude\//.test(cmd)) return "gravito_search";
    if (resultIsError) return "tool_retry";
    return "product_work";
  }

  if (resultIsError) return "tool_retry";
  return "unclassified";
}

/** Walk a stream, returning per-cause turn counts. */
export function causesForStream(streamPath) {
  let ev = [];
  try {
    ev = fs.readFileSync(streamPath, "utf8").split("\n").filter(Boolean)
      .map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
  } catch { return null; }

  const use = {};
  for (const e of ev) for (const c of (e?.message?.content || []))
    if (c.type === "tool_use") use[c.id] = { name: c.name, input: c.input || {} };

  const counts = Object.fromEntries(CAUSES.map((c) => [c, 0]));
  const chars = Object.fromEntries(CAUSES.map((c) => [c, 0]));
  let toolCalls = 0;
  for (const e of ev) for (const c of (e?.message?.content || [])) {
    if (c.type !== "tool_result") continue;
    const u = use[c.tool_use_id];
    if (!u) continue;
    toolCalls++;
    const body = typeof c.content === "string" ? c.content : JSON.stringify(c.content || "");
    const cause = classifyTurn(u.name, u.input, c.is_error === true, body);
    counts[cause]++; chars[cause] += body.length;
  }
  const res = ev.find((e) => e.type === "result") || {};
  return { counts, chars, toolCalls, turns: res.num_turns ?? null };
}

export function aggregate(runsDir, filter) {
  const agg = { arms: 0, turns: 0, toolCalls: 0,
                counts: Object.fromEntries(CAUSES.map((c) => [c, 0])),
                chars: Object.fromEntries(CAUSES.map((c) => [c, 0])) };
  for (const d of fs.readdirSync(runsDir).sort()) {
    if (!filter(d)) continue;
    const m = causesForStream(path.join(runsDir, d, "stream.jsonl"));
    if (!m) continue;
    agg.arms++; agg.turns += m.turns || 0; agg.toolCalls += m.toolCalls;
    for (const c of CAUSES) { agg.counts[c] += m.counts[c]; agg.chars[c] += m.chars[c]; }
  }
  return agg;
}
